// Turns game/game.html (the same file as the web prototype) into game/gameHtml.ts for the app.
// Run after every change to the game:  npm run build:game
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
let body = fs.readFileSync(path.join(root, 'game', 'game.html'), 'utf8');

// The app works offline and sends nothing to other servers, so drop the web-font links.
// iOS falls back to Arial Rounded and the system font.
body = body.replace(/<link[^>]+fonts\.(googleapis|gstatic)\.com[^>]*>\s*/g, '');
body = body.replace(/<title>[\s\S]*?<\/title>\s*/, '').replace(/<meta name="claude:[^>]*>\s*/g, '');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>Bubble Bases</title>
<style>
html { background: #ffffff; box-sizing: border-box; padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
*, *::before, *::after { box-sizing: inherit; }
body { margin: 0; font-size: 14px; -webkit-text-size-adjust: 100%; -webkit-tap-highlight-color: transparent; -webkit-touch-callout: none; }
img { max-width: 100%; }
[hidden] { display: none !important; }
</style>
</head>
<body>
${body}
</body>
</html>
`;

const out = `// Generated by scripts/build-game.js from game/game.html. Do not edit by hand.\nconst gameHtml: string = ${JSON.stringify(html)};\nexport default gameHtml;\n`;
fs.writeFileSync(path.join(root, 'game', 'gameHtml.ts'), out);
fs.writeFileSync(path.join(root, 'web', 'app-preview.html'), html);
console.log('Built game/gameHtml.ts (' + Math.round(out.length / 1024) + ' KB)');
